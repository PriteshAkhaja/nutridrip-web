// Ports the home page preview (scrollcraft/builds/home-v5) into the app's home route.
//
//   npm run home-port
//
// Run it after any change to the preview. It writes, and overwrites (never edit them by hand):
//   src/components/site/home/v5/port/markup.ts    the page's markup (inside <main>; the site's own header and
//                                                 footer stand in for the preview's)
//   src/components/site/home/v5/port/home-v5.css  the stylesheet, scoped to `.sc-site .hv5`, in @layer site
//   src/components/site/home/v5/port/home-v5.js   the page's script, as mountHome(root, data) → destroy()
//   src/components/site/home/v5/port/dose-gl.js   the dose act's WebGL renderer, as a module
//   public/site/home/                             the images and the two fonts the site does not already load
//
// The preview stays the place the page is designed: it runs on its own copy of the data, and the app passes its
// real data (src/lib/data/home-v5.ts) in place of window.NUTRIDRIP_HOME.
//
// Why each step:
// - The stylesheet resets html, body, * and sets its own :root tokens. Unscoped it would restyle the site's header
//   and footer and outlive the route after a client-side navigation, so every selector is moved under the wrapper
//   (`:root`, `html`, `body` → the wrapper; the classes the script sets on <html>, `js` and `still`, → on the
//   wrapper), keyframes are renamed hv5-*, and the site's own Outfit and Geist faces are used rather than loaded twice.
// - The script attached window listeners, timers, animation frames, observers and a WebGL context. The port tracks
//   every one and undoes them in destroy(), and puts the markup back, so a client-side navigation and React's
//   development double-mount leave nothing running and nothing changed.
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const SRC = "scrollcraft/builds/home-v5";
const OUT = "src/components/site/home/v5/port";
const PUB = "public/site/home";
const URL = "/site/home/";
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(PUB + "/fonts", { recursive: true });
const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8").replace(/\r\n/g, "\n");
const HEAD = (what) =>
  `// GENERATED by scripts/port-home-v5.mjs from ${SRC}/${what}. Do not edit: change the preview and run \`npm run home-port\`.\n`;
const imgs = (s) => s.replace(/(["'(=\s])images\//g, `$1${URL}`);

/* ------------------------------------------------------------------ markup */
const html = read("index.html");
const main = html.slice(html.indexOf('<main id="top">') + '<main id="top">'.length, html.indexOf("</main>"));
const markup = imgs(main.replace(/<!--[\s\S]*?-->/g, ""))
  .replace(/\n\s*\n+/g, "\n")
  .trim();
fs.writeFileSync(`${OUT}/markup.ts`, HEAD("index.html") + `export const HOME_V5_HTML = ${JSON.stringify(markup)};\n`);

/* ------------------------------------------------------------------ stylesheet */
const ROOT = ".sc-site .hv5";
const WRAPPER = ["js", "still"];
const SITE_FACES = ["Geist", "Outfit"];
const css = postcss.parse(read("styles.css"));
const frames = new Map();
css.walkAtRules("keyframes", (r) => {
  frames.set(r.params, "hv5-" + r.params);
  r.params = "hv5-" + r.params;
});
css.walkAtRules("font-face", (r) => {
  let fam = "";
  r.walkDecls("font-family", (d) => {
    fam = d.value.replace(/["']/g, "");
  });
  if (SITE_FACES.includes(fam)) r.remove();
});
const scope = (sel) => {
  sel = sel.trim();
  if (sel === ":root" || sel === "html" || sel === "body") return ROOT;
  let m;
  if ((m = /^(html|body)(\S*)(.*)$/.exec(sel))) return ROOT + m[2] + m[3];
  if ((m = /^\.(\w[\w-]*)(.*)$/.exec(sel)) && WRAPPER.includes(m[1])) return ROOT + "." + m[1] + m[2];
  return ROOT + " " + sel;
};
css.walkRules((r) => {
  if (r.parent?.type === "atrule" && /keyframes$/.test(r.parent.name)) return;
  r.selectors = r.selectors.map(scope);
});
css.walkDecls((d) => {
  if (/^animation(-name)?$/.test(d.prop))
    for (const [a, b] of frames) d.value = d.value.replace(new RegExp(`(^|[\\s,])${a}(?=$|[\\s,])`, "g"), `$1${b}`);
  if (d.value.includes("url("))
    d.value = d.value
      .replace(/url\((["']?)images\//g, `url($1${URL}`)
      .replace(/url\((["']?)fonts\//g, `url($1${URL}fonts/`);
});
const faces = [],
  body = [];
css.each((n) => (n.type === "atrule" && n.name === "font-face" ? faces : body).push(n.toString()));
fs.writeFileSync(
  `${OUT}/home-v5.css`,
  `/* GENERATED by scripts/port-home-v5.mjs from ${SRC}/styles.css. Do not edit: change the preview and run \`npm run home-port\`. */\n` +
    faces.join("\n") +
    "\n@layer site {\n" +
    body.join("\n") +
    "\n}\n"
);

/* ------------------------------------------------------------------ the dose renderer */
let gl = read("dose-gl.js");
const glStart = gl.indexOf("(function () {");
gl = gl.slice(0, glStart) + "export var DoseGL = " + gl.slice(glStart);
gl = gl.replace("window.DoseGL = { create: create };", "return { create: create };");
if (!gl.includes("return { create: create };")) throw new Error("dose-gl.js: the export line moved");
fs.writeFileSync(`${OUT}/dose-gl.js`, HEAD("dose-gl.js") + "/* eslint-disable */\n" + gl);

/* ------------------------------------------------------------------ the page's script */
let js = read("app.js");
const must = (from, to) => {
  if (!js.includes(from)) throw new Error("app.js: cannot find " + JSON.stringify(from.slice(0, 60)));
  js = js.split(from).join(to);
};
const PRELUDE = `
  // (port) Everything this page starts, it can stop: listeners on window, timers, animation frames, observers.
  var dead = false, offs = [], rafs = new Set(), tos = new Set(), obs = [], ORIGINAL = ROOT.innerHTML;
  var listen = function (t, ty, fn, o) { t.addEventListener(ty, fn, o); offs.push(function () { t.removeEventListener(ty, fn, o); }); };
  var requestAnimationFrame = function (f) { if (dead) return 0; var id = window.requestAnimationFrame(function (t) { rafs.delete(id); if (!dead) f(t); }); rafs.add(id); return id; };
  var setTimeout = function (f, ms) { if (dead) return 0; var id = window.setTimeout(function () { tos.delete(id); if (!dead) f(); }, ms); tos.add(id); return id; };
  var clearTimeout = function (id) { tos.delete(id); window.clearTimeout(id); };
  var IntersectionObserver = function (cb, o) { var x = new window.IntersectionObserver(cb, o); obs.push(x); return x; };
  var ResizeObserver = function (cb) { var x = new window.ResizeObserver(cb); obs.push(x); return x; };
`;
const EPILOGUE = `
  // (port) Undo it all, and put the markup back as it was served.
  return function destroy() {
    dead = true;
    offs.forEach(function (f) { f(); });
    rafs.forEach(function (id) { window.cancelAnimationFrame(id); });
    tos.forEach(function (id) { window.clearTimeout(id); });
    obs.forEach(function (o) { o.disconnect(); });
    if (ds.gl && ds.gl.dispose) ds.gl.dispose();
    ROOT.classList.remove("still");
    ROOT.innerHTML = ORIGINAL;
  };
}
`;
must('(function () {\n  "use strict";\n', 'export function mountHome(ROOT, DATA) {\n  "use strict";\n' + PRELUDE);
js = js.replace(/\}\)\(\);\s*$/, EPILOGUE);
if (!js.includes("return function destroy()")) throw new Error("app.js: the closing line moved");
must("var root = document.documentElement;", "var root = ROOT;");
must("return (r || document).querySelector(s);", "return (r || ROOT).querySelector(s);");
must("(r || document).querySelectorAll(s)", "(r || ROOT).querySelectorAll(s)");
must("window.NUTRIDRIP_HOME", "DATA");
must(
  '(m.addEventListener ? m.addEventListener("change", function () { setStill(); kick(); }) : m.addListener(setStill))',
  'listen(m, "change", function () { setStill(); kick(); })'
);
must("window.addEventListener(", "listen(window, ");
must("window.DoseGL && !isStill()", "DoseGL && !isStill()");
must("getComputedStyle(document.documentElement)", "getComputedStyle(ROOT)");
must(
  "document.fonts.ready.then(function () { measure(); kick(); })",
  "document.fonts.ready.then(function () { if (!dead) { measure(); kick(); } })"
);
js = imgs(js).replace(/url\(images\//g, `url(${URL}`);
for (const left of ["window.addEventListener(", "document.documentElement", "window.DoseGL", "images/"])
  if (js.includes(left)) throw new Error("app.js: still has " + left);
fs.writeFileSync(
  `${OUT}/home-v5.js`,
  HEAD("app.js") + '/* eslint-disable */\nimport { DoseGL } from "./dose-gl.js";\n' + js
);

/* ------------------------------------------------------------------ images and fonts */
// Every image the page can ask for: named in the markup, stylesheet or scripts, or built from a prefix there
// ("field-" + item, "morning-" + goal, "dose-" + part + size).
const used = new Set(),
  text = html + read("styles.css") + read("app.js") + read("dose-gl.js");
const PREFIXES = ["field-", "morning-", "dose-", "ink-", "doc-"];
for (const f of fs.readdirSync(path.join(SRC, "images")))
  if (text.includes("images/" + f) || PREFIXES.some((p) => f.startsWith(p))) used.add(f);
for (const f of fs.readdirSync(PUB))
  if (fs.statSync(path.join(PUB, f)).isFile() && !used.has(f)) fs.rmSync(path.join(PUB, f));
for (const f of used) fs.copyFileSync(path.join(SRC, "images", f), path.join(PUB, f));
for (const f of ["newsreader-var.woff2", "newsreader-italic.woff2", "geist-mono.woff2"])
  fs.copyFileSync(path.join(SRC, "fonts", f), path.join(PUB, "fonts", f));
for (const f of fs.readdirSync(path.join(SRC, "fonts")))
  if (/^OFL|LICENSE/i.test(f)) fs.copyFileSync(path.join(SRC, "fonts", f), path.join(PUB, "fonts", f));
console.log(
  `home port: markup ${(markup.length / 1024).toFixed(0)} KB, ${used.size} images, keyframes renamed ${frames.size}`
);
