// Scopes the public site's stylesheets to the `.sc-site` wrapper.
//
//   npm run site-css
//
// Run it after editing any source below. It writes
// src/components/site/v3/styles/scoped/*.css, which the routes import. Never
// edit the scoped files: they are overwritten.
//
// The sources are the scroll-craft engine's CSS (copied unchanged from the
// skill; never edited per page) and the client's stylesheets ported from the
// approved prototypes (scrollcraft/builds/home-v3, iv-vs-tablets, drip-v3,
// drips-v3) and the pages built straight in the app since (hiw for How it
// works, safety, about, clinics, pricing, zones, consult, faqs, legal), and
// account for sign-in and /welcome.
// Unscoped, they reset html, body, * and img and set their own :root tokens: they would
// restyle the patient app and the consoles, and outlive the route after a
// client-side navigation. So every selector is moved under the wrapper:
//
//   :root, html-only props ....... :root:has(.sc-site)  (only while a site page is open)
//   body .......................... .sc-site
//   body.x / .is-static ... ....... .sc-site.x          (classes page scripts set on the wrapper)
//   .sc-ready X ................... .sc-ready .sc-site X (the engine sets sc-ready on <html>)
//   anything else ................. .sc-site <selector>
//
// and the result sits in `@layer site`, which globals.css orders after base
// and before components and utilities: site rules beat Tailwind's preflight,
// never a utility, so `.sc-site a { color: inherit }` cannot repaint a
// `text-white` button on a page not yet redesigned.
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const ROOT = ".sc-site";
const ENGINE = "src/components/site/scroll/engine/scrollcraft.css";
const STYLES = "src/components/site/v3/styles";
const SOURCES = [
  [ENGINE, "engine.css"],
  [`${STYLES}/site.css`, "site.css"],
  [`${STYLES}/home.css`, "home.css"],
  [`${STYLES}/ivtabs.css`, "ivtabs.css"],
  [`${STYLES}/glass.css`, "glass.css"],
  [`${STYLES}/drip.css`, "drip.css"],
  [`${STYLES}/drip-build.css`, "drip-build.css"],
  [`${STYLES}/fcard.css`, "fcard.css"],
  [`${STYLES}/drips.css`, "drips.css"],
  [`${STYLES}/hiw.css`, "hiw.css"],
  [`${STYLES}/safety.css`, "safety.css"],
  [`${STYLES}/about.css`, "about.css"],
  [`${STYLES}/clinics.css`, "clinics.css"],
  [`${STYLES}/pricing.css`, "pricing.css"],
  [`${STYLES}/zones.css`, "zones.css"],
  [`${STYLES}/consult.css`, "consult.css"],
  [`${STYLES}/faqs.css`, "faqs.css"],
  [`${STYLES}/legal.css`, "legal.css"],
  [`${STYLES}/account.css`, "account.css"],
];
// Classes that a page script puts on the wrapper (the prototypes put them on
// <body>), so `.is-static .x` must read `.sc-site.is-static .x`.
const WRAPPER_CLASSES = ["is-static", "nd-js", "nd-tinted", "nd-gated"];

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  // :root tokens and resets: the wrapper carries them.
  if (/^:root\b/.test(s)) return s.replace(/^:root/, ROOT);
  // html: only properties that must sit on the document (scroll padding,
  // smooth scrolling), and only while a site page is mounted.
  if (/^html(?=$|[\s.:[])/.test(s)) return s.replace(/^html/, `:root:has(${ROOT})`);
  if (/^body(?=$|[\s.:[])/.test(s)) return s.replace(/^body/, ROOT);
  if (/^\.sc-ready(?=$|[\s.:[])/.test(s)) return s.replace(/^\.sc-ready/, `.sc-ready ${ROOT}`);
  for (const c of WRAPPER_CLASSES) {
    const re = new RegExp(`^\\.${c}(?=$|[\\s.:[>+~])`);
    if (re.test(s)) return s.replace(re, `${ROOT}.${c}`);
  }
  if (s.startsWith(ROOT)) return s;
  // The universal reset reaches the wrapper itself too.
  if (/^\*/.test(s)) return `${ROOT}${s.slice(1)}, ${ROOT} ${s}`;
  return `${ROOT} ${s}`;
}

function insideKeyframes(node) {
  for (let p = node.parent; p; p = p.parent) if (p.type === "atrule" && /keyframes$/i.test(p.name)) return true;
  return false;
}

fs.mkdirSync(`${STYLES}/scoped`, { recursive: true });
for (const [src, out] of SOURCES) {
  const root = postcss.parse(fs.readFileSync(src, "utf8"), { from: src });
  root.walkRules((rule) => {
    if (insideKeyframes(rule)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
  });
  // @font-face and @keyframes stay global (outside the layer): they are
  // named resources, not rules that cascade onto elements.
  const hoisted = [];
  root.each((node) => {
    if (node.type === "atrule" && /^(font-face|keyframes|-webkit-keyframes)$/i.test(node.name)) hoisted.push(node);
  });
  hoisted.forEach((n) => n.remove());
  const header = `/* GENERATED by scripts/scope-site-css.mjs from ${src}. Do not edit: edit the source and run \`npm run site-css\`. */\n`;
  const body = root.toString().trim();
  const css = `${header}${hoisted.map((n) => n.toString()).join("\n")}\n@layer site {\n${body}\n}\n`;
  fs.writeFileSync(path.join(STYLES, "scoped", out), css);
  console.log(`${out}: ${root.nodes.length} top-level nodes, ${hoisted.length} hoisted`);
}
