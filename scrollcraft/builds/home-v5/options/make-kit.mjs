// Builds options/kit.js from ../app.js: the drip data and the code that draws the labelled glass and bags, taken
// verbatim, so the option previews show the page's own drips, vials and bags. Run after changing app.js:
//   node scrollcraft/builds/home-v5/options/make-kit.mjs
import fs from "node:fs";
import path from "node:path";
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const app = fs.readFileSync(path.join(here, "../app.js"), "utf8").replace(/\r\n/g, "\n");
const cut = (from, to) => {
  const a = app.indexOf(from),
    b = app.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error("app.js: cannot find " + (a < 0 ? from : to));
  return app.slice(a, b);
};
const helpers =
  cut("  var clamp = function", "  var root = document.documentElement;") +
  cut("  var money = function", "  /* ------------------------------------------------------------------ data */");
const data = cut("  var GOALS = D.goals ||", "  var ZONES = D.zones ||");
const words = cut("  var WORDS = [", "  var COUNTS = ");
const glass = cut(
  "  /* ------------------------------------------------------------------ glass and bag */",
  "  // no picture on the page is picked up"
);
const body = (helpers + "  var D = {};\n" + data + words + glass).replace(/(["'(])images\//g, "$1../images/");
fs.writeFileSync(
  path.join(here, "kit.js"),
  "/* GENERATED by options/make-kit.mjs from ../app.js: the drips and the labelled glass and bags, for the option previews. */\n" +
    'window.KIT = (function () {\n  "use strict";\n' +
    body +
    "\n  return { DRIPS: DRIPS, GOALS: GOALS, FIRST: FIRST, byId: byId, money: money, clamp: clamp, ss: ss, morningOf: morningOf, word: word, upFirst: upFirst,\n" +
    "    glassEl: glassEl, ingHTML: ingHTML, labelHTML: labelHTML, bagHTML: bagHTML, bandsFor: bandsFor, isC: isC, AMP: AMP, VIAL: VIAL, VITC: VITC };\n})();\n"
);
console.log("kit.js written");
